-- V20260826_05/_06 的第三个兄弟: 派生的百分比列没跟着清。
--
-- ## 它是怎么留下来的
--
-- V20260826_05 把编出来的 good_quantity(= actual, 声称零不良) 清成 NULL,
-- V20260826_06 补了孪生的 defect_quantity。**但两条都只清了「分子」**,
-- 而 yield_rate = good/actual 这个【派生百分比】原样留着 ——
-- 它现在是那批假数据唯一还活着的残留。
--
-- 🔴 而且是【永久冻结】的: ProductionBatch.calculateFields() 里的守卫是
--    `if (goodQuantity != null && actualQuantity != null && actual > 0)`,
--    good 全库清空之后这个分支【永远进不去】⇒ 旧值再也不会被重算。
--
-- ## 生产实测 (cretas_prod_db, 2026-08-28)
--
--   · 全库 46 个批次, good_quantity 非空的行数 = 【0】(8-26 清完之后没人补过)
--   · 而 yield_rate 非空的有 【40】 行 ⇒ 40 行「没有分子却有结果」
--   · 其中 39 行恰好 = 100.00, 1 行 = 60.00
--   · 31 行连 actual_quantity 都是 NULL 且 status = IN_PROGRESS
--     —— 实际产量都还没有, 良品率却已经 100%
--
-- ### 两条可直接证伪 (不是口径不同, 是同一定义下算出来就不等)
--
--   批次 10766: 计划 80 盒 / 实际 75 盒, 质检记了 5 件不合格 ⇒ 按定义 93.75%, 字段写 100.00
--   批次 10786: 计划 5 盒 / 实际 4 盒                        ⇒ 按定义 80.00%, 字段写 100.00
--
-- ### 阳性对照
--
--   · 这一列【能】存 100 以外的值(批次 10760 存着 60.00) ⇒ 「几乎全是 100」不是字段坏了
--   · 同一段代码里的邻居 efficiency 在 38 个批次上是 NULL(算不出就留空, 诚实的)
--     ⇒ 两个字段同方法同守卫结构而结果一空一满, 说明 100 不是这次算的, 是冻住的
--
-- ## 为什么可以整批清
--
-- 判据是【分子为空】, 不是【值等于 100】: 只要 good_quantity IS NULL,
-- 这个百分比就没有任何东西支撑它, 不管它写着多少。
-- ⛔ 所以那行 60.00 也一并清 —— 它同样没有分子。
--
-- ## 为什么这不丢信息
--
-- 被清的值全部可从 good/actual 重算, 而这两列原样保留。
-- 只要有人真的录了良品数, calculateFields() 会立刻把它算回来
-- (本 PR 同时给那个 else 分支补了 `yieldRate = null`, 所以往后不会再冻住)。
--
-- ## 读侧安全性
--
--   · 消费方全部 null-safe(`getYieldRate() != null` 守卫), 清成 NULL 不会让任何调用点炸。
--   · ⚠️ 唯一的例外 ProcessingServiceImpl.getWeeklyBatchesCost 把 null 兜底成 BigDecimal.ZERO,
--     【本 PR 同时改掉】—— 不改的话这次清洗会把「假的 100%(完美)」变成「假的 0%(全废)」,
--     比现在更糟。
--
-- ## 保守性 / 幂等
--
-- ⛔ 只清 good_quantity IS NULL 的行。将来真有人录了良品数, 本迁移【不碰】它。
-- 重复执行不再匹配任何行。
--
-- ### ⚠️ 命中行数是一个【在涨】的数, 不要引用一个定值
--
--   2026-08-28 00:2x 实测 ... 40 行
--   2026-08-28 01:0x 实测 ... 50 行   (同一条 WHERE, 40 分钟后)
--
-- 涨的原因是【缺陷还在持续产生新数据】: 每建一个批次就多一行「没有分子却有百分比」。
-- ⇒ 上线时实际命中数会比 50 更大, 这是正常的, 不是判据不符。
-- ⛔ 别拿「命中了 N 行」当验收判据 —— 验收判据见下面「上线后核什么」。
--
-- 试算(只读, 2026-08-28 01:0x, cretas_prod_db):
--   将被清空 .............. 50 行
--   有分子而被跳过的 ...... 0 行     ← 零误伤
--   阴性对照(假工厂) ...... 0 行     ← 这把尺子不是见谁都匹配
--   涉及工厂 .............. 1 个 (F006)
--
-- ## 上线后核什么
--
--   1. `SELECT count(*) FROM production_batches WHERE yield_rate IS NOT NULL AND good_quantity IS NULL`
--      必须是 **0**, 并且【此后保持 0】—— 保持 0 才证明代码侧那个 else 分支真的接上了,
--      只清一次数据的话它第二天就会重新长出来。
--   2. 阳性对照: 同一把尺子在 `good_quantity IS NOT NULL` 上仍能数出行(若有人录了良品数),
--      否则「0 行」可能只是查询本身失效。

UPDATE production_batches
   SET yield_rate = NULL,
       updated_at = now()
 WHERE yield_rate IS NOT NULL
   AND good_quantity IS NULL;
