CREATE TABLE tool_metadata (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tool_name           VARCHAR(100)     NOT NULL,
    action_type         VARCHAR(20)      NOT NULL DEFAULT 'READ',
    risk_level          VARCHAR(20)      NOT NULL DEFAULT 'LOW',
    domain_tags         TEXT             DEFAULT '[]',
    tool_version        VARCHAR(20)      DEFAULT '1.0.0',
    deprecation_notice  TEXT,
    last_called_at      TIMESTAMP(6),
    call_count          BIGINT           NOT NULL DEFAULT 0,
    success_count       BIGINT           NOT NULL DEFAULT 0,
    failure_count       BIGINT           NOT NULL DEFAULT 0,
    avg_execution_ms    DOUBLE PRECISION DEFAULT 0,
    created_at          TIMESTAMP(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at          TIMESTAMP(6),
    CONSTRAINT uk_tool_metadata_tool_name UNIQUE (tool_name)
);

CREATE INDEX idx_tm_action_type ON tool_metadata (action_type);
CREATE INDEX idx_tm_risk_level  ON tool_metadata (risk_level);
CREATE INDEX idx_tm_last_called ON tool_metadata (last_called_at);

COMMENT ON TABLE tool_metadata IS 'Tool 治理元数据: 调用统计 + 风险/领域标签 + 废弃标记 (SkillManageTool deprecate_tool/reactivate_tool 读写)';
COMMENT ON COLUMN tool_metadata.deprecation_notice IS 'NULL=活跃, 非 NULL=已废弃(含原因)';

-- 断言: 建出来的列集合必须与实体 ToolMetadata(+BaseEntity) 一一对上; 不对就红着停。
DO $$
DECLARE
    expected TEXT[] := ARRAY[
        'id','tool_name','action_type','risk_level','domain_tags','tool_version',
        'deprecation_notice','last_called_at','call_count','success_count','failure_count',
        'avg_execution_ms','created_at','updated_at','deleted_at'];
    actual   TEXT[];
BEGIN
    SELECT array_agg(column_name::text ORDER BY column_name) INTO actual
      FROM information_schema.columns
     WHERE table_schema = 'public' AND table_name = 'tool_metadata';
    IF actual IS NULL OR actual <> (SELECT array_agg(x ORDER BY x) FROM unnest(expected) x) THEN
        RAISE EXCEPTION 'V20261101_36: tool_metadata 列集合与实体不一致, expected=% actual=%', expected, actual;
    END IF;
    RAISE NOTICE 'V20261101_36: tool_metadata 建表完成, % 列', array_length(actual, 1);
END $$;
