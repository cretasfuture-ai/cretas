package com.cretas.aims.service.reports;

import com.cretas.aims.dto.MobileDTO;
import com.cretas.aims.entity.AIAnalysisResult;
import org.springframework.stereotype.Component;

/** Explicit fail-closed projection, with @PriceSensitive response fields as a second guard. */
@Component
public class OperatingReportProjection {
    private final OperatingReportCodec codec;
    public OperatingReportProjection(OperatingReportCodec codec){this.codec=codec;}
    public MobileDTO.AICostAnalysisResponse detail(AIAnalysisResult report,boolean canViewPrices) {
        var snapshot=codec.decode(report.getAnalysisText());
        String publicText=snapshot.map(s->codec.render(s,false)).orElse("历史成本报告；财务正文按价格权限提供。");
        String financialText=canViewPrices?snapshot.map(s->codec.render(s,true)).orElse(report.getAnalysisText()):null;
        boolean failed=snapshot.map(s->s.status()==OperatingReportSnapshot.Status.FAILED).orElse(false);
        String reason=failed?codec.failure(snapshot.orElseThrow()).reason():null;
        String code=failed?codec.failure(snapshot.orElseThrow()).name():null;
        return MobileDTO.AICostAnalysisResponse.builder().reportId(report.getId())
                .success(!failed).analysis(publicText).reportAnalysis(financialText)
                .generationStatus(failed?"FAILED":"SUCCESS").failureCode(code).errorMessage(reason)
                .cacheHit(true).processingTimeMs(0L).generatedAt(report.getCreatedAt()).expiresAt(report.getExpiresAt()).build();
    }
    public MobileDTO.AIReportSummary summary(AIAnalysisResult report,boolean canViewPrices) {
        MobileDTO.AICostAnalysisResponse detail=detail(report,canViewPrices);
        return MobileDTO.AIReportSummary.builder().id(report.getId()).batchId(report.getBatchId()).reportType(report.getReportType())
                .summaryText(shorten(detail.getAnalysis())).financialSummaryText(shorten(detail.getReportAnalysis()))
                .generationStatus(detail.getGenerationStatus()).failureCode(detail.getFailureCode()).failureReason(detail.getErrorMessage())
                .periodStart(report.getPeriodStart()).periodEnd(report.getPeriodEnd()).createdAt(report.getCreatedAt())
                .expiresAt(report.getExpiresAt()).isAutoGenerated(report.getIsAutoGenerated()).build();
    }
    private String shorten(String text){return text==null?null:text.length()>200?text.substring(0,200)+"…":text;}
}
