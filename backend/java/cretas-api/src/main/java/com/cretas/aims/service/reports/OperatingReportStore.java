package com.cretas.aims.service.reports;

import com.cretas.aims.entity.AIAnalysisResult;
import com.cretas.aims.repository.AIAnalysisResultRepository;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Propagation;
import org.springframework.transaction.annotation.Transactional;
import java.time.LocalDate;
import java.time.LocalDateTime;
import java.util.List;

/** Independent transaction keeps a failure visible even when the generating transaction rolls back. */
@Service
public class OperatingReportStore {
    private final AIAnalysisResultRepository repository;
    private final OperatingReportCodec codec;
    public OperatingReportStore(AIAnalysisResultRepository repository,OperatingReportCodec codec){this.repository=repository;this.codec=codec;}

    @Transactional(propagation=Propagation.REQUIRES_NEW)
    public AIAnalysisResult save(String factoryId,OperatingReportSnapshot snapshot,boolean automatic) {
        return repository.saveAndFlush(AIAnalysisResult.builder().factoryId(factoryId)
                .reportType(snapshot.reportType()).dimension("operating-v1")
                .analysisText(codec.encode(snapshot)).periodStart(LocalDate.parse(snapshot.periodStart()).atStartOfDay())
                .periodEnd(LocalDate.parse(snapshot.periodEnd()).atTime(23,59,59))
                .expiresAt(LocalDateTime.now().plusDays("monthly".equals(snapshot.reportType())?90:30))
                .isAutoGenerated(automatic).build());
    }

    @Transactional(propagation=Propagation.REQUIRES_NEW)
    public AIAnalysisResult failure(String factoryId,String type,LocalDate start,LocalDate end,
                                    OperatingReportSnapshot.Failure reason,boolean automatic,OperatingReportSnapshot.AuditReceipt audit) {
        return save(factoryId,new OperatingReportSnapshot(OperatingReportSnapshot.SCHEMA,
                OperatingReportSnapshot.Status.FAILED,type,start.toString(),end.toString(),LocalDateTime.now().toString(),
                List.of(),List.of(),List.of(),reason,audit),automatic);
    }
}
