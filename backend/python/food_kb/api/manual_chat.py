# Token budget (improvement #5)
# ---------------------------------------------------------------------------

# Answer-token budget per depth tier. The depth selector (MVP / 中度 / 全量) is the
# user's explicit statement of how much SOP surface they want, so it — not the length
# of the question — decides the budget.
#
# Measured basis (prod python-prod.log, 2026-08-19, slot=chat):
#   completion=1200, 1200, 1199   pinned exactly at the old cap ⇒ the cap was binding
#   completion=567                a naturally-finished answer   ⇒ short answers stop early
#   1200 tokens in 7.9s / 10.3s wall                            ⇒ ~120-150 tok/s
#   1200-token answers measured 1955/1977/1925 chars            ⇒ ~1.63 Chinese chars/token
#   one probe at max_tokens=4000 stopped naturally at 1970 tokens (finish_reason=stop)
#
# ⚠️ max_tokens is a CAP, not a reservation — cost and latency follow the tokens
# actually generated. Raising it costs nothing on answers that already stop early;
# the only added spend is the tail that used to be cut off mid-sentence.
#
# Ceiling rationale: 3000 tokens is ~20-25s at the measured rate, which still fits
# inside the 30s non-stream timeout used by the /manual-chat fallback path below.
# Going higher would trade 'truncated answer' for 'AI 服务暂时不可用' on that path —
# a strictly worse failure. The primary path (/manual-chat/stream) uses an idle-based
# client timeout, so it is not the binding constraint.
_DEPTH_MAX_TOKENS = {
    "mvp": 1200,     # 最小闭环: 正常业务 + 必要审批 (~1950 字)
    "medium": 2000,  # + 四类基础拓扑 / 缺料采购 / 完整调拨 / 关键成本 (~3260 字)
    "full": 3000,    # + 冲突 / 异常 / 质检 / 冲销 / ECN / 治理审计 (~4900 字)
}


def _estimate_max_tokens(depth: SopDepth) -> int:
    """Answer-token budget, decided by the user's depth selection.

    ⚠️ This used to key off the *question text* (300/600/1200 by keyword + length)
    while the depth selector was not an input at all — so 全量 and MVP received the
    same budget and full-depth answers were cut off mid-sentence. Depth is now the
    only input; see _DEPTH_MAX_TOKENS for the measured basis of each tier.

    The factory assistant uses the default depth (model default "mvp"), so it gets 1200 — which
    is >= every value the old heuristic could return, so that path cannot regress.

    Indexes directly rather than using .get(): depth is a validated Literal, so an
    unknown value is a contract violation that should fail loudly, not silently
    fall back to a smaller budget (which would look exactly like the bug above).
    """
    return _DEPTH_MAX_TOKENS[depth]


