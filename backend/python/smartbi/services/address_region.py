_COUNTRY_PREFIXES: tuple[str, ...] = ("中华人民共和国", "中国")

# 地名后面紧跟「路 / 街 / 大道…」说明这是路名 (「中山北路」「北京东路」「南京路」),
# 不是行政区, 不能据此归省。
_STREET_AFTER_NAME = re.compile(r"^[东西南北中]?(?:路|街|大街|大道|巷|弄)")


def _starts_with_place(text: str, name: str) -> bool:
    return text.startswith(name) and not _STREET_AFTER_NAME.match(text[len(name):])


def province_short_of(address: Optional[str]) -> Optional[str]:
    """返回地址所属省级行政区的简称 (如 ``"江苏"``); 识别不了返回 ``None``。"""
    if address is None:
        return None
    text = "".join(str(address).split())
    for prefix in _COUNTRY_PREFIXES:
        if text.startswith(prefix):
            text = text[len(prefix):]
            break
    if not text:
        return None
    for short, _full in PROVINCES:
        if _starts_with_place(text, short):
            return short
    for city in _CITY_KEYS:
        if _starts_with_place(text, city):
            return _CITY_TO_PROVINCE[city]
    return None


def province_full_name(short: str) -> str:
    return _FULL_BY_SHORT[short]


def big_region_of(short: str) -> str:
    return _BIG_REGION_BY_SHORT[short]
