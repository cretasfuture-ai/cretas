"""Generate the catalog migration without changing model IDs or tenant permissions."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CATALOG = ROOT / "backend/java/cretas-api/src/main/resources/ai/factory-intent-catalog.json"
TARGET = ROOT / "backend/java/cretas-api/src/main/resources/db/flyway/V20261104_32__factory_intent_catalog_retirement.sql"


def render() -> str:
    catalog = json.loads(CATALOG.read_text(encoding="utf-8"))
    payload = json.dumps(catalog, ensure_ascii=False, separators=(",", ":"))
    assert "$factory_catalog$" not in payload
    assert "${" not in payload, "Catalog text must not contain Flyway placeholders"
    return """-- Generated by scripts/ai/generate_factory_intent_migration.py; do not edit by hand.
-- Configuration retirement only. No business documents, model mappings, or training history are deleted.
-- Flyway executes this file in one transaction; the temporary catalog is transaction-local.
ALTER TABLE ai_intent_configs ADD COLUMN IF NOT EXISTS metadata jsonb;
ALTER TABLE ai_intent_configs ADD COLUMN IF NOT EXISTS previous_snapshot jsonb;
-- The legacy bootstrap declared these JSON documents as TEXT. Align them with
-- the existing Entity JSONB contract; malformed legacy JSON fails closed.
ALTER TABLE ai_intent_configs ALTER COLUMN keywords TYPE jsonb USING NULLIF(btrim(keywords::text), '')::jsonb;
ALTER TABLE ai_intent_configs ALTER COLUMN required_roles TYPE jsonb USING NULLIF(btrim(required_roles::text), '')::jsonb;
CREATE TEMP TABLE factory_catalog_patch (document jsonb NOT NULL) ON COMMIT DROP;
INSERT INTO factory_catalog_patch VALUES ($factory_catalog$
""" + payload + """
$factory_catalog$::jsonb);

-- Preserve the previous configuration for audit; rerunning does not replace that snapshot.
UPDATE ai_intent_configs i
SET previous_snapshot = COALESCE(i.previous_snapshot, to_jsonb(i)),
    is_active = false, deleted_at = COALESCE(i.deleted_at, CURRENT_TIMESTAMP),
    updated_at = CURRENT_TIMESTAMP
FROM factory_catalog_patch p
WHERE i.intent_code LIKE 'RESTAURANT\\_%' ESCAPE '\\'
   OR p.document->'retired_intents' ? i.intent_code
   OR p.document->'aliases' ? i.intent_code;

-- Only the reviewed reclassification/binding overrides are patched. Tenant scope,
-- approval chains, explicit disabled/deleted states and other permission fields survive.
UPDATE ai_intent_configs i
SET previous_snapshot = COALESCE(i.previous_snapshot, to_jsonb(i)),
    business_type = CASE WHEN p.document->'reclassified_intents' ? i.intent_code
                         THEN c.value->>'business_type' ELSE i.business_type END,
    tool_name = c.value->>'tool_name',
    sensitivity_level = CASE WHEN c.value->>'execution_policy' IN ('AUTOMATIC_INVOICING_ONLY', 'NAVIGATION_ONLY')
                             THEN 'LOW' ELSE i.sensitivity_level END,
    requires_approval = CASE WHEN c.value->>'execution_policy' IN ('AUTOMATIC_INVOICING_ONLY', 'NAVIGATION_ONLY')
                             THEN false ELSE i.requires_approval END,
    description = COALESCE(c.value->>'description', i.description),
    required_roles = CASE WHEN c.value->>'audience' = 'PLATFORM_ADMIN'
                          THEN '["super_admin","platform_admin","developer"]'::jsonb
                          ELSE i.required_roles END,
    metadata = COALESCE(i.metadata, '{}'::jsonb) || jsonb_build_object(
        'factory_catalog_version', 1, 'skill_name', c.value->'skill_name'),
    updated_at = CURRENT_TIMESTAMP
FROM factory_catalog_patch p,
     LATERAL jsonb_array_elements(p.document->'canonical_intents') c(value)
WHERE i.intent_code = c.value->>'intent_code'
  AND (p.document->'reclassified_intents' ? i.intent_code
       OR COALESCE((c.value->>'binding_override')::boolean, false)
       OR c.value->>'audience' = 'PLATFORM_ADMIN');

-- Merge only recognition phrases, never the alias permissions or activation state.
UPDATE ai_intent_configs target
SET keywords = (SELECT COALESCE(jsonb_agg(DISTINCT word), '[]'::jsonb)
                FROM jsonb_array_elements(COALESCE(target.keywords, '[]'::jsonb)
                     || COALESCE(alias.keywords, '[]'::jsonb)) word),
    updated_at = CURRENT_TIMESTAMP
FROM ai_intent_configs alias, factory_catalog_patch p
WHERE p.document->'aliases'->>alias.intent_code = target.intent_code
  AND target.factory_id IS NOT DISTINCT FROM alias.factory_id;

UPDATE ai_intent_phrase_registry r
SET status = 'REJECTED', updated_at = CURRENT_TIMESTAMP
FROM factory_catalog_patch p
WHERE r.intent_code LIKE 'RESTAURANT\\_%' ESCAPE '\\'
   OR p.document->'retired_intents' ? r.intent_code;

UPDATE ai_intent_phrase_registry r
SET intent_code = p.document->'aliases'->>r.intent_code, updated_at = CURRENT_TIMESTAMP
FROM factory_catalog_patch p
WHERE p.document->'aliases' ? r.intent_code;

-- A pre-existing FACTORY/COMMON phrase wins a key collision. The old-domain row
-- remains rejected in place for audit; no reviewed decision is manufactured.
UPDATE ai_intent_phrase_registry r
SET status = 'REJECTED', updated_at = CURRENT_TIMESTAMP
FROM factory_catalog_patch p,
     LATERAL jsonb_array_elements(p.document->'canonical_intents') c(value)
WHERE (p.document->'reclassified_intents' ? r.intent_code
       OR EXISTS (SELECT 1 FROM jsonb_each_text(p.document->'aliases') a(old_code, new_code)
                  WHERE a.new_code = r.intent_code AND p.document->'reclassified_intents' ? a.old_code))
  AND r.intent_code = c.value->>'intent_code'
  AND r.business_type <> c.value->>'business_type'
  AND EXISTS (SELECT 1 FROM ai_intent_phrase_registry other
              WHERE other.factory_id = r.factory_id
                AND other.business_type = c.value->>'business_type'
                AND other.normalized_text = r.normalized_text);

UPDATE ai_intent_phrase_registry r
SET business_type = c.value->>'business_type', updated_at = CURRENT_TIMESTAMP
FROM factory_catalog_patch p,
     LATERAL jsonb_array_elements(p.document->'canonical_intents') c(value)
WHERE (p.document->'reclassified_intents' ? r.intent_code
       OR EXISTS (SELECT 1 FROM jsonb_each_text(p.document->'aliases') a(old_code, new_code)
                  WHERE a.new_code = r.intent_code AND p.document->'reclassified_intents' ? a.old_code))
  AND r.intent_code = c.value->>'intent_code'
  AND r.business_type <> c.value->>'business_type'
  AND NOT EXISTS (SELECT 1 FROM ai_intent_phrase_registry other
                  WHERE other.factory_id = r.factory_id
                    AND other.business_type = c.value->>'business_type'
                    AND other.normalized_text = r.normalized_text);

UPDATE smart_bi_skill s SET enabled = false, updated_at = CURRENT_TIMESTAMP
FROM factory_catalog_patch p
WHERE s.name LIKE 'restaurant-%'
   OR EXISTS (SELECT 1 FROM jsonb_array_elements_text(COALESCE(s.tools, '[]'::jsonb)) t(name)
              WHERE t.name LIKE 'restaurant\\_%' ESCAPE '\\'
                 OR p.document->'retired_tools' ? t.name);

-- Read-only catalog skills must not inherit a persisted legacy write DAG.
-- Runtime additionally validates classpath, DB and per-factory overrides.
UPDATE smart_bi_skill s
SET tools = c.value->'skill_tools',
    config = COALESCE(s.config, '{}'::jsonb) - 'steps' - 'executionGraph' - 'execution',
    updated_at = CURRENT_TIMESTAMP
FROM factory_catalog_patch p,
     LATERAL jsonb_array_elements(p.document->'canonical_intents') c(value)
WHERE s.name = c.value->>'skill_name'
  AND COALESCE((c.value->>'skill_read_only')::boolean, false);
"""


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != expected:
            raise SystemExit("Generated factory catalog migration is stale")
    else:
        TARGET.write_text(expected, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
