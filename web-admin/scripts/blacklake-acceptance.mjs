  assert.equal(await page.getByTestId('eligible-cost-review').locator('.el-table__body-wrapper tbody tr').count(),8);
  await page.locator('.el-select').filter({has:page.getByRole('combobox',{name:'异常类别',exact:true})}).locator('.el-select__wrapper').click();
  await page.getByRole('option',{name:'成本差异信号',exact:true}).click();
  assert.equal(await page.getByTestId('cost-alert-table').locator('.el-table__body-wrapper tbody tr').count(),5);
  assert((await page.getByTestId('cost-alert-table').innerText()).includes('25.0%'));
  await page.screenshot({path:join(privateDir,'smartbi-cost-alert-signals.png'),fullPage:true});
  await page.locator('.el-select').filter({has:page.getByRole('combobox',{name:'异常类别',exact:true})}).locator('.el-select__wrapper').click();
  await page.getByRole('option',{name:'全部类别',exact:true}).click();
