import { chromium } from '@playwright/test';
import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve, join } from 'node:path';
import assert from 'node:assert/strict';

const base = 'http://127.0.0.1:5178';
const root = resolve(import.meta.dirname, '../..');
const privateDir = join(process.env.LOCALAPPDATA, 'Cretas', 'Blacklake', 'validation');
mkdirSync(privateDir, { recursive: true });
const script = "import json,os;from pathlib import Path;from blacklake.secrets import load_local_secret;d=Path(os.environ['LOCALAPPDATA'])/'Cretas/Blacklake';s=load_local_secret(d/'smartbi-test.dpapi');a=load_local_secret(d/'smartbi-analysis.dpapi');p=sorted([r for r in a['cost']['projects'] if r['unitCostAvailable']],key=lambda r:r['materialLines'],reverse=True)[0];hint=next(r for r in a['costAlerts']['items'] if r['type']=='INPUT_ONLY_CONSUMABLES');print(json.dumps({'username':s['username'],'password':s['password'],'validProjectCode':p['projectCode'],'packagingProjectCode':hint['entityRefs'][0]['projectCode']}))";
