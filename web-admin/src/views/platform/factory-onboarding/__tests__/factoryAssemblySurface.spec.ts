import { describe, expect, it } from 'vitest'
import { readFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

describe('Agent 工厂装配主流程入口', () => {
  const here = dirname(fileURLToPath(import.meta.url))
  const page = readFileSync(resolve(here, '..', 'index.vue'), 'utf8')
  const api = readFileSync(resolve(here, '..', '..', '..', '..', 'api', 'factoryOnboardingApi.ts'), 'utf8')
  const preview = readFileSync(resolve(here, '..', 'components', 'FactoryAssemblyPreview.vue'), 'utf8')
  const editor = readFileSync(resolve(here, '..', 'components', 'FactoryAssemblyDetailEditor.vue'), 'utf8')
  const conservation = readFileSync(resolve(here, '..', 'factoryAssemblyIntentConservation.ts'), 'utf8')
  const processTable = readFileSync(resolve(here, '..', 'components', 'FactoryConversationProcessTable.vue'), 'utf8')
  const processDetails = readFileSync(resolve(here, '..', 'components', 'FactoryConversationProcessDetails.vue'), 'utf8')
  const productTable = readFileSync(resolve(here, '..', 'components', 'FactoryConversationProductTable.vue'), 'utf8')
  const domainCard = readFileSync(resolve(here, '..', 'components', 'FactoryConversationDomainCard.vue'), 'utf8')
  const receipt = readFileSync(resolve(here, '..', 'components', 'FactoryConversationReceipt.vue'), 'utf8')

  it('代表性样例、结构化信息卡和矛盾反问在同一条对话流程中', () => {
    expect(page).toContain('讲一个代表产品')
    expect(page).toContain('对话中的信息卡')
    expect(page).toContain('用一个代表性产品')
    expect(page).toContain('FactoryConversationProductTable')
    expect(page).toContain('FactoryConversationDomainCard')
    expect(productTable).toContain('Agent 成品组合确认')
    expect(domainCard).toContain('每个项目都需要明确选择或回答')
    expect(page).toContain('class="preference-disclosure"')
    expect(page).toContain('按需展开')
    expect(page).toContain('我先帮你反问一遍')
    expect(page).toContain('blockingIssues.length')
  })

  it('剩余工序细节按一道工序分组，支持采纳建议、没有和整卡返回', () => {
    expect(page).toContain('FactoryConversationProcessDetails')
    expect(page).toContain('activeProcessDetails')
    expect(page).toContain('submitProcessDetails')
    expect(page).toContain("kind: 'field-card'")
    expect(page).toContain('currentItemInProcessDetails')
    expect(processDetails).toContain('一次只看一道工序')
    expect(processDetails).toContain('采纳：')
    expect(processDetails).toContain('>没有</el-button>')
    expect(processDetails).toContain('把这道工序的细节交给 Agent')
  })

  it('AI 消息携带可编辑工序表，结构化结果回到 Agent 并留在对话历史', () => {
    expect(page).toContain('FactoryConversationProcessTable')
    expect(page).toContain('FactoryConversationReceipt')
    expect(page).toContain('submitProcessTable')
    expect(page).toContain("kind: 'process-table'")
    expect(page).toContain("kind: 'choice-card'")
    expect(processTable).toContain('Agent 可操作表格')
    expect(processTable).toContain('确认这张表并继续')
    expect(processTable).toContain("emit('updateRow'")
    expect(receipt).toContain('已发送给 Agent')
    expect(receipt).toContain('Agent 处理回执')
    expect(page).toContain('extractionReceiptEntries')
    expect(page).toContain('这句话的字段处理结果')
  })

  it('同一道确定性问题只在批量问卷出现一次，语言区只保留例外补充入口', () => {
    expect(page).toContain('currentItem && !currentItemInStructuredCard')
    expect(page).toContain('isChoice && !currentItemInStructuredCard')
    expect(page).toContain('当前这题已经放在上方对话信息卡里')
    expect(page).toContain('当前这题已经放在上方工序细节卡里')
    expect(page).toContain('当前这题已经放在上方流程表里')
    expect(page).toContain('组件里不好表达？直接补充：')
  })

  it('请求失败保留上下文、说明副作用并提供原位重试', () => {
    expect(page).toContain('这句话没有送达，输入已经放回编辑框')
    expect(page).toContain('draft.value = text')
    expect(page).toContain('信息卡没有送达，已选答案仍然保留')
    expect(page).toContain('流程表没有送达，刚才的修改仍然保留')
    expect(page).toContain('工序细节卡没有送达，刚才的内容仍然保留')
    expect(page).toContain('retryFlowIssue')
    expect(page).toContain('正在写入 · 请勿刷新')
  })

  it('低频对话和预览仅在普通偏好下使用短促合成层动效，减弱动态时完全停止', () => {
    const visualSurface = [page, preview, productTable, domainCard].join('\n')
    expect(page).toContain('animation: turn-enter 220ms var(--assembly-ease-out)')
    expect(preview).toContain('animation: preview-enter 240ms var(--preview-ease-out)')
    expect(preview).toContain('@media (hover: hover) and (pointer: fine)')
    expect(visualSurface).toContain('@media (prefers-reduced-motion: reduce)')
    expect(page).toContain(':global(body *), :global(body *::before), :global(body *::after)')
    expect(page).toContain('animation: none !important')
    expect(page).toContain('transition-duration: 0s !important')
    expect(page).not.toContain('turn-fade')
    expect(visualSurface).not.toContain('transition: all')
    expect(visualSurface).not.toMatch(/transition:[^;]*(width|height|margin|padding)/)
  })

  it('结构化填写区有键盘焦点反馈，移动端给表格和选项卡更多可用宽度', () => {
    expect(page).toContain('.preference-disclosure summary:focus-visible')
    expect(page).toContain('.structured-bubble:focus-within')
    expect(productTable).toContain('.product-row:not(.product-header):focus-within')
    expect(domainCard).toContain('.domain-field:focus-within')
    expect(page).toContain('.turn { gap: 6px; max-width: 96%; }')
    expect(page).toContain("'steps--conversation': step === 0")
    expect(page).toContain('.steps--conversation { display: none; }')
  })

  it('窄屏能力目录按单列顺序阅读，不依赖难发现的横向滑动', () => {
    const mobileStart = preview.indexOf('@media (max-width: 520px)')
    const mobileEnd = preview.indexOf('@media (prefers-reduced-motion: reduce)', mobileStart)
    const mobile = preview.slice(mobileStart, mobileEnd)
    expect(mobile).toContain('grid-template-columns: minmax(0, 1fr)')
    expect(mobile).not.toContain('scroll-snap-type')
    expect(mobile).not.toContain('overflow-x: auto')
  })

  it('直接链接只有工厂 ID 时仍回填客户可读名称，失败不阻断访谈', () => {
    expect(page).toContain('hydrateSelectedFactoryName')
    expect(page).toContain('authStore.factoryId === factoryId.value')
    expect(page).toContain('factoryName.value = authStore.factoryName')
    expect(page).toContain('factory.id === factoryId.value')
    expect(page).toContain('名称回填失败只影响展示，不阻断访谈')
  })

  it('工厂总管理员从菜单进入自己的蓝图，不误请求平台工厂列表', () => {
    const mountedAt = page.indexOf('onMounted(async () => {')
    const mounted = page.slice(mountedAt, page.indexOf('</script>', mountedAt))
    expect(mounted).toContain("authStore.currentRole === 'factory_super_admin'")
    expect(mounted).toContain('factoryId.value = authStore.factoryId')
    expect(mounted).toContain('factoryName.value = authStore.factoryName || authStore.factoryId')
    expect(mounted.indexOf("authStore.currentRole === 'factory_super_admin'")).toBeLessThan(
      mounted.indexOf('else await loadFactories()'),
    )
  })

  it('选择工厂和直链进入都在访谈前加载服务端默认配置', () => {
    const startAt = page.indexOf('async function start(forceRestart = false)')
    const conversationAt = page.indexOf('startFactoryBuildConversation(factoryId.value, forceRestart)', startAt)
    const defaultsAt = page.indexOf('await loadAlertCatalog()', startAt)
    expect(defaultsAt).toBeGreaterThan(startAt)
    expect(defaultsAt).toBeLessThan(conversationAt)
    expect(page).toContain('start()')
  })

  it('刷新恢复服务端 ACTIVE 会话、消息与失败草稿，只有明确重新开始才新建', () => {
    expect(api).toContain('startFactoryBuildConversation(factoryId: string, forceRestart = false)')
    expect(api).toContain("params: { forceRestart: true }")
    expect(page).toContain('res.data.history ?? []')
    expect(page).toContain('if (res.data.resumed) draft.value = readStoredDraft()')
    expect(page).toContain('sessionStorage.setItem(draftStorageKey(), value.slice(0, 10_000))')
    expect(page).toContain('sessionStorage.removeItem(draftStorageKey())')
    expect(page).toContain('await start(true)')
    expect(page).toContain('ElMessageBox.confirm(')
    expect(page).toContain('当前访谈已确认 ${answered} 项、还剩 ${remaining} 项')
    expect(page).toContain('确认创建新访谈')
  })

  it('工序数常用值可快选，更多入口收敛在 1-30 且提交真实数字', () => {
    expect(page).toContain("const STEP_COUNT_MORE_OPTION = '更多（1-30）'")
    expect(page).toContain(':min="1"')
    expect(page).toContain(':max="30"')
    expect(page).toContain('step-strictly')
    expect(page).toContain('useStepCountMoreInQuestionnaire')
    expect(page).toContain('submitStepCountMore')
    expect(page).toContain('String(stepCountMoreValue.value)')
  })

  it('最新完成会话优先于旧蓝图恢复，并解释动态展开造成的进度变化', () => {
    expect(api).toContain('getRecoverableFactoryBuildConversation')
    expect(api).toContain('/ai-initialize/converse/recoverable')
    expect(page).toContain('hydrateRecoverableConversation')
    expect(page).toContain("recoverable.status === 'COMPLETED'")
    expect(page).toContain('recoverable.sessionId !== blueprintSessionId')
    expect(page).toContain('clearFlowIssue()')
    expect(page).toContain('ElMessage.closeAll()')
    expect(page).toContain('generationFailureDetail(errorMessage(error))')
    expect(page).toContain("step.value = 0")
    expect(page).toContain('已按数量展开 ${delta} 个细节项')
    expect(page).toContain('进度百分比可能暂时下降')
    expect(page).toContain('role="status" aria-live="polite"')
  })

  it('平台管理员从工厂选择器进入时也先恢复权威蓝图和会话，不直接新建', () => {
    const chooseAt = page.indexOf('async function chooseFactory()')
    const hydrateAt = page.indexOf('await hydrateFactoryWorkspace()', chooseAt)
    const startAt = page.indexOf('await start()', chooseAt)
    expect(chooseAt).toBeGreaterThan(-1)
    expect(hydrateAt).toBeGreaterThan(chooseAt)
    expect(startAt === -1 || hydrateAt < startAt).toBe(true)
    expect(page).toContain('restoreConversationMessages')
  })

  it('预览同时给能力装配图、覆盖图和产品工艺图', () => {
    expect(page).toContain('FactoryAssemblyPreview')
    expect(page).toContain(':blueprint="canonicalBlueprint"')
    expect(preview).toContain('blueprint.schemaVersion')
    expect(preview).toContain('{{ configurationStateLabel }}')
    expect(preview).toContain('{{ workflowStateLabel }}')
    expect(preview).toContain('formalConfigurationLabel(blueprint.value.configurationState, props.formalExecutions ?? {})')
    expect(preview).toContain('formalWorkflowLabel(blueprint.value.workflowState, props.formalExecutions ?? {})')
    expect(preview).toContain('blueprint.capabilityCatalogVersion')
    expect(preview).toContain('blueprint.capabilityCatalogDigest')
    expect(preview).toContain('catalog.digest !== blueprint.value.capabilityCatalogDigest')
    expect(preview).toContain('已锁定 ${props.catalog.capabilityCount} 项不可变能力定义')
    expect(preview).toContain('配置对象：')
    expect(preview).toContain('关联模块：')
    expect(preview).toContain('适用行业与重点场景')
    expect(preview).toContain('查看依据与研究映射')
    expect(preview).toContain('S01 · GB 14881-2013')
    expect(preview).toContain('S04 · GB 8957-2016')
    expect(preview).toContain('S04 · GB 12695-2016')
    expect(preview).toContain('S04 · GB 31646-2018')
    expect(preview).toContain('FROZEN_PREPARED_CENTRAL_KITCHEN')
    expect(preview).toContain('.evidence-button:focus-visible')
    expect(preview).toContain('min-height: 44px')
    expect(preview).toContain(':visible="openEvidenceCapabilityId === capability.id"')
    expect(preview).toContain('@update:visible="setEvidencePopoverVisibility(capability.id, $event)"')
    expect(preview).toContain('@keydown.esc.stop.prevent="closeEvidencePopover"')
    expect(preview).toContain('const openEvidenceCapabilityId = ref<string | null>(null)')
    expect(preview).toContain('服务端持久化并回读的权威蓝图')
    expect(preview).toContain('平台能力装配图')
    expect(preview).toContain('等待补齐依赖')
    expect(preview).toContain('missingDependencies')
    expect(preview).toContain('装配覆盖图')
    expect(preview).toContain('产品路线图')
    expect(preview).toContain('已保存路线契约')
    expect(preview).toContain('线性路线兼容视图')
    expect(preview).toContain('Array.isArray(route.routeNodes) || Array.isArray(route.routeEdges)')
    expect(preview).toContain('routeGraphs')
    expect(preview).toContain("REWORK: '返工'")
  })

  it('生成后允许编辑全部装配域，修改必须重新保存并回读权威草稿', () => {
    expect(page).toContain('FactoryAssemblyDetailEditor')
    expect(editor).toContain('Array.isArray(route.routeNodes) || Array.isArray(route.routeEdges)')
    expect(editor).toContain('.el-button:focus-visible')
    expect(editor).toContain('outline: 3px solid #1b65a8')
    expect(page).toContain('专业复核（可选）')
    expect(page).toContain('日常流程不要求填写这些表')
    expect(page.indexOf('FactoryAssemblyPreview')).toBeLessThan(page.indexOf('FactoryAssemblyDetailEditor'))
    expect(page).toContain('await saveAuthoritativeDraft()')
    expect(page).toContain('saveCanonicalFactoryBlueprintDraft(factoryId.value')
    expect(page).toContain('const authoritativeSessionId = canonicalViewMode.value')
    expect(page).toContain('const authoritativeCustomerSupplied = canonicalViewMode.value')
    expect(page).toContain('conversionEvidence: generated.value.suggestedData.conversionRates.map')
    expect(page).toContain('response.data.plannedChanges')
    expect(page).toContain('previewValidationState.title')
    expect(page).toContain('权威草稿已保存，尚未执行业务一致性验证')
    expect(page).toContain('serverBlockingIssues')
    expect(page).toContain('必须修正后才能继续')
    expect(page).toContain('pendingDecisionCount')
    expect(editor).toContain('产品、原料与包装')
    expect(editor).toContain('业务类别')
    expect(editor).toContain('FINISHED_PRODUCT')
    expect(conservation).toContain("productCategory: product.productCategory?.trim() || 'FINISHED_PRODUCT'")
    expect(editor).toContain('工序、配方与产品路线')
    expect(editor).toContain('复杂路线')
    expect(editor).toContain('分支')
    expect(editor).toContain('合流')
    expect(editor).toContain('返工')
    expect(editor).toContain('addRouteNode')
    expect(editor).toContain('addRouteEdge')
    expect(editor).toContain('HACCP 与关键控制点')
    expect(editor).toContain('存放区与物料编码')
    expect(editor).toContain('模块、阈值、账号与指标')
    expect(editor).toContain('告警与异常指标')
    expect(editor).toContain('业务表单模板')
    expect(editor).toContain('完整配置（专业模式）')
  })

  it('预览修改不会被问卷里的旧告警与指标值二次覆盖', () => {
    const payloadStart = page.indexOf('function buildApplyPayload()')
    const payloadEnd = page.indexOf('function markPreviewDirty()', payloadStart)
    const payload = page.slice(payloadStart, payloadEnd)
    expect(payload).not.toContain('alerts: collectAlerts()')
    expect(payload).not.toContain('metricWatches: collectMetricWatches()')
    expect(payload).toContain('fromCode: conversion.fromCode')
    expect(payload).not.toContain('provenance: conversion.provenance')
  })

  it('写入和 Workflow 发布分开，发布入口使用真实产品 id', () => {
    expect(page).toContain('确认应用配置')
    expect(page).toContain('发布蓝图版本')
    expect(page).toContain('不应用配置、不发布 Workflow')
    expect(page).toContain('核对并发布 {{ lane.productName }} Workflow')
    expect(page).toContain('resolveProductTypeIdByCode')
    expect(page).toContain("name: 'ProductProcesses'")
    expect(preview).toContain('此刻未发布')
  })

  it('权威状态按验证、零写模拟、蓝图发布和显式应用逐步解锁', () => {
    const validateAt = page.indexOf('validateCanonicalFactoryBlueprint(')
    const simulateAt = page.indexOf('simulateCanonicalFactoryBlueprint(')
    const publishAt = page.indexOf('publishCanonicalFactoryBlueprint(')
    const applyAt = page.indexOf('applyCanonicalFactoryBlueprint(')
    expect(validateAt).toBeGreaterThan(-1)
    expect(simulateAt).toBeGreaterThan(validateAt)
    expect(publishAt).toBeGreaterThan(simulateAt)
    expect(applyAt).toBeGreaterThan(-1)
    expect(page).toContain("canonicalBlueprint?.lifecycleState === 'DRAFT'")
    expect(page).toContain("canonicalBlueprint?.lifecycleState === 'PUBLISHED'")
    expect(page).toContain('ElMessageBox.confirm(')
    expect(page).toContain('业务配置写入为 0')
  })

  it('页面重载读取服务端蓝图，失败时明确禁止本地摘要降级', () => {
    expect(page).toContain('getCurrentCanonicalFactoryBlueprint(factoryId.value)')
    expect(page).toContain('await hydrateCanonicalBlueprint()')
    expect(page).toContain('不会退回浏览器本地摘要')
    expect(page).toContain('const sourcePayload = candidate.sourcePayload')
    expect(page).toContain('const provenanceByPair = new Map(')
    expect(page).toContain('await refreshProgress()')
    expect(page).toContain('processSkeletonPersisted(snapshot)')
    expect(page).toContain('productFlowPersisted(snapshot)')
    expect(page).toContain('FactoryConversationFactLedger')
    expect(page).toContain('factEvidence')
    expect(page).toContain("/^product\\d+\\.(name|steps|routeShape|routeDetails)$/")
    expect(page).toContain("canResumeConversation.value")
    expect(page).toContain('开始新的访谈版本')
    expect(preview).not.toContain('capabilityCards(')
    expect(preview).not.toContain('blueprintDraftSummary(')
    expect(preview).toContain('authoritativeBlockedCount')
    expect(preview).toContain('权威草稿已保存，尚未验证')
  })

  it('写入成功后的推荐顺序固定为先逐屏复核、再发布 Workflow', () => {
    const review = page.indexOf('先逐屏复核这次配了什么')
    const workflow = page.indexOf('复核之后：逐个核对并发布产品 Workflow')
    expect(review).toBeGreaterThan(-1)
    expect(workflow).toBeGreaterThan(review)
    expect(page).toContain('复核页只读，不会再次写库')
  })
})
