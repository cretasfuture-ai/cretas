/**
 * 出成报工「可投上限约 N」这句提示里那个 N 的格式化。
 *
 * <h2>为什么单独一个模块</h2>
 *
 * 原来它是内联的 `Math.round(plannedMax)`。2026-08-29 在小米真机上走报工链时实测：
 *
 * ```
 * 工序 SOP-20260817-01-黄油鸡-原料处理, 计划数量 0.04 kg
 * 弹窗提示:  「计划 0.04 kg, 可投上限约 0 (含 30% 超收)」
 * 实际提交 0.04 kg -> 成功
 * ```
 *
 * `Math.round(0.04 * 1.3)` = `Math.round(0.052)` = **0**。
 *
 * ⛔ 真正生效的 `plannedMax` **没有取整**（0.052），只有这句**显示**取整成了 0
 *    ⇒ 界面对操作员说的和系统实际拦的是两个数，而且不报错。
 *    凡是计划量 < 约 0.385 的工序，操作员看到的都是「可投上限约 0」——
 *    那不是一个近似值，那是「一点都不能投」这句话。
 *
 * ⚠️ 它能活这么久，是因为唯一被检验过的例子是大数量：
 *    组件 docstring 里写的是「计划 998 kg, 可投上限约 1297」——
 *    那个量级上取整无害。**小量级从来没有人看过。**
 *
 * ⚠️ 同族教训（本仓多次）：兜底/取整会把一个真实的小数翻译成 `0`，
 *    而 `0` 对下游（这里是"人"）的含义和"很小"完全不同。
 */

/**
 * 把数量格式化成给操作员看的字符串。
 *
 * ⛔ 不变式：**正数永远不会被格式化成 "0"**。
 * 这条不变式就是这个模块存在的全部理由，改实现时先跑那条断言。
 *
 * - `1297.4` → `"1297"`（大量级取整，与既有文案一致）
 * - `0.052`  → `"0.052"`
 * - `0.00052`→ `"0.00052"`（极小量走有效数字，不许被压成 0）
 */
export function formatQtyHint(value: number): string {
  if (!Number.isFinite(value)) {
    return String(value);
  }
  const abs = Math.abs(value);
  if (abs === 0) {
    return '0';
  }
  if (abs >= 100) {
    return String(Math.round(value));
  }
  if (abs < 0.01) {
    // 有效数字, 否则 toFixed 会把它压成 "0.000"
    return String(Number(value.toPrecision(2)));
  }
  return String(Number(value.toFixed(abs >= 1 ? 2 : 3)));
}
